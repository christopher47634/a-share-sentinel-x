/** Shanghai calendar date (YYYY-MM-DD), independent of server/browser timezone. */
export function shanghaiDate(date: Date = new Date()): string {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
}
